test('all four untimed new guided flows allow skipping and finishing without saving ratings', async ({ page }) => {
  await page.goto('./#today')
  const stored = await page.evaluate(() => ({ ...localStorage }))
  await page.getByRole('button', { name: 'Real-Time Support', exact: true }).click()
  for (const [index, count] of [[6,5],[7,4],[8,6],[9,6]]) {
    const row = page.locator('.rts-tool').nth(index)
    await row.locator(':scope > .inline-expansion > button').click()
    await expect(row.getByRole('button', { name: 'Start Guided Practice', exact: true })).toBeDisabled()
    await row.getByLabel('I am stationary and not doing a safety-critical task.').check()
    await row.getByRole('button', { name: 'Start Guided Practice', exact: true }).click()
    for (let i = 0; i < count; i++) {
      await expect(row.locator('.rts-current-step')).toHaveCount(1)
      await row.getByRole('button', { name: 'Skip step', exact: true }).click()
    }
    await expect(row.getByText('Practice finished. No particular outcome is expected.', { exact: true })).toBeVisible()
    await row.getByRole('button', { name: 'Stop practice', exact: true }).click()
  }
  expect(await page.evaluate(() => ({ ...localStorage }))).toEqual(stored)
})
