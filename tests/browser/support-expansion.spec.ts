test('urge ratings accept 0 and 10 optionally, surface withdrawal safety and never persist', async ({ page }) => {
  await page.goto('./#today')
  const stored = await page.evaluate(() => ({ ...localStorage }))
  await page.getByRole('button', { name: 'Real-Time Support', exact: true }).click()
  const row = page.locator('.rts-tool').nth(8)
  await row.locator(':scope > .inline-expansion > button').click()
  await expect(row.locator('.rts-urgent-safety')).toContainText('withdrawal', { timeout: 1500 })
  const before = row.getByLabel('Before practice — urge intensity (optional, 0–10)', { exact: true })
  await before.selectOption('0')
  await row.getByLabel('I am stationary and not doing a safety-critical task.').check()
  await row.getByRole('button', { name: 'Start Guided Practice', exact: true }).click()
  await row.getByRole('button', { name: 'Next step', exact: true }).click()
  await expect(before).toHaveValue('0')
  for (let i = 1; i < 6; i++) await row.getByRole('button', { name: i === 5 ? 'Finish practice' : 'Next step', exact: true }).click()
  await row.getByLabel('After practice — urge intensity (optional, 0–10)', { exact: true }).selectOption('10')
  expect(await page.evaluate(() => ({ ...localStorage }))).toEqual(stored)
  await row.getByRole('button', { name: 'Stop practice', exact: true }).click()
  await expect(before).toHaveValue('')
  await row.getByLabel('I am stationary and not doing a safety-critical task.').check()
  await row.getByRole('button', { name: 'Start Guided Practice', exact: true }).click()
  await row.getByRole('button', { name: 'Connect With Support', exact: true }).click()
  await expect(page.locator('#support-title')).toBeVisible()
  await expect(page.locator('#rts-title')).toHaveCount(0)
})


test('favourites persist only allowlisted IDs, reopen tools and honour existing clear-all', async ({ page }) => {
  await page.goto('./#today')
  await page.getByRole('button', { name: 'Real-Time Support', exact: true }).click()
  const row = page.locator('.rts-tool').nth(5)
  await row.locator(':scope > .inline-expansion > button').click()
  await row.getByRole('button', { name: 'Save Physical Tension Reset as favourite', exact: true }).click({ timeout: 1500 })
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('path-to-rise-realtime-favourites-v1')!))).toEqual(['physical-tension-reset'])
  await page.reload()
  await page.getByRole('button', { name: 'Real-Time Support', exact: true }).click()
  await page.getByText('Favourite tools (1)', { exact: true }).click()
  await page.getByRole('button', { name: 'Open favourite: Physical Tension Reset', exact: true }).click()
  await expect(row.getByRole('button', { name: 'Remove Physical Tension Reset from favourites', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Exit Real-Time Support', exact: true }).click()
  await page.getByRole('button', { name: 'Your space', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Clear all local prototype data', exact: true }).click()
  expect(await page.evaluate(() => localStorage.getItem('path-to-rise-realtime-favourites-v1'))).toBeNull()
})

