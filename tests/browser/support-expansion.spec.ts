import { test, expect } from '@playwright/test'

const newNames = ['Physical Tension Reset', 'Control and Confidence Reset', 'Re-Engagement Reset', 'Urge and Craving Reset', 'Self-Compassion and Accountability Reset']

test('ten independent support tools retain original order and add the five requested names', async ({ page }) => {
  await page.goto('./#today')
  await page.getByRole('button', { name: 'Real-Time Support', exact: true }).click()
  await expect(page.locator('.rts-tool')).toHaveCount(10, { timeout: 1500 })
  for (let i = 0; i < newNames.length; i++) {
    const row = page.locator('.rts-tool').nth(i + 5)
    await expect(row.locator(':scope > .inline-expansion > button')).toHaveAccessibleName(newNames[i])
    await row.locator(':scope > .inline-expansion > button').click()
    await expect(row.locator('h2')).toHaveText(['What', 'When', 'How', 'Why', 'Benefits', 'Duration', 'Adaptations', 'Scientific References'])
  }
})


for (const minutes of [2, 5]) test(`PMR ${minutes} minutes uses gentle 5/10 pacing, optional skipped areas and real cleanup`, async ({ page }) => {
  await page.goto('./#today')
  await page.clock.install({ time: new Date('2026-01-01T00:00:00Z') })
  await page.clock.pauseAt(new Date('2026-01-01T00:00:10Z'))
  await page.getByRole('button', { name: 'Real-Time Support', exact: true }).click()
  const row = page.locator('.rts-tool').nth(5)
  await row.locator(':scope > .inline-expansion > button').click()
  await row.getByLabel(`${minutes} minutes`, { exact: true }).check({ timeout: 1500 })
  await row.getByLabel('Skip shoulders', { exact: true }).check()
  await row.getByLabel('I am stationary and not doing a safety-critical task.').check()
  await row.getByRole('button', { name: 'Start Guided Practice', exact: true }).click()
  await row.getByRole('button', { name: 'Next step', exact: true }).click()
  const pace = row.locator('.rts-pmr')
  await expect(pace).toHaveAttribute('data-phase', 'prepare')
  await page.clock.fastForward(minutes === 2 ? 10000 : 20000)
  await expect(pace).toHaveAttribute('data-phase', 'tense')
  await expect(pace).toHaveAttribute('data-area', 'hands')
  await page.clock.fastForward(5000)
  await expect(pace).toHaveAttribute('data-phase', 'release')
  await page.clock.fastForward(10000)
  await expect(pace).toHaveAttribute('data-area', 'shoulders')
  await expect(pace).toHaveAttribute('data-phase', 'rest')
  await row.getByRole('button', { name: 'Pause practice', exact: true }).click()
  const remaining = await row.getByLabel('Practice time remaining').textContent()
  await page.clock.fastForward(900000)
  await expect(row.getByLabel('Practice time remaining')).toHaveText(remaining!)
  await row.getByRole('button', { name: 'Resume practice', exact: true }).click()
  await page.clock.fastForward(minutes * 60000)
  await expect(row.getByRole('button', { name: 'Finish practice', exact: true })).toBeVisible()
  await row.getByRole('button', { name: 'Stop practice', exact: true }).click()
  await page.clock.fastForward(900000)
  await expect(pace).toHaveCount(0)
  await expect(row.getByLabel('Before practice (optional, 0–10)')).toHaveValue('')
})


