test('reminder preferences save without requesting system permission', async ({ page }) => {
  await page.addInitScript(() => {
    Object.assign(window, { reminderPermissionCalls: 0 })
    if ('Notification' in window) Object.defineProperty(Notification, 'requestPermission', { configurable: true, value: async () => { Object.assign(window, { reminderPermissionCalls: 1 }); return 'denied' } })
  })
  await page.goto('/#today')
  await page.getByRole('button', { name: 'Your space', exact: true }).click()
  await page.locator('.notification-settings > summary').click()
  const group = page.locator('.reminder-group').filter({ has: page.locator('#program-reminder-title') })
  await group.locator(':scope > summary').click()
  await group.getByRole('button', { name: 'Off', exact: true }).click()
  await group.locator('input[type=time]').fill('09:10')
  const practice = page.locator('.reminder-group').filter({ has: page.locator('#practice-reminder-title') })
  await practice.locator(':scope > summary').click()
  await practice.getByRole('combobox').selectOption({ index: 1 })
  await practice.getByRole('button', { name: 'Off', exact: true }).click()
  const prefs = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), notificationStorageKey)
  expect(prefs.programReminder.enabled).toBe(true)
  expect(prefs.programReminder.schedule.time).toBe('09:10')
  expect(prefs.practiceReminder.enabled).toBe(true)
  expect(prefs.practiceReminder.targetToolId).toBeTruthy()
  expect(await page.evaluate(() => Reflect.get(window, 'reminderPermissionCalls'))).toBe(0)
  await page.reload()
  await page.getByRole('button', { name: 'Your space', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your space', exact: true })).toBeVisible()
  await page.locator('.notification-settings > summary').click()
  await expect(page.locator('#program-reminder-title')).toBeVisible()
  await expect(page.locator('.reminder-group').first().locator('input[type=time]')).toHaveValue('09:10')
})
