test('approved A keeps Reset first and starts the real source-backed day', async ({ page }) => {
  await page.goto('/#today')
  await expect(page.getByRole('heading', { name: 'Leave the shift. Keep yourself.' })).toBeVisible()
  const reset = page.getByRole('button', { name: 'Reset me now', exact: true })
  const path = page.locator('.today-a-path')
  await expect(reset).toBeVisible()
  expect(await reset.evaluate((el) => el.getBoundingClientRect().top)).toBeLessThan(await path.evaluate((el) => el.getBoundingClientRect().top))
  await expect(path).toContainText('Day 1 of 28')
  await expect(path).toContainText('Set your alarm')
  await expect(path.getByRole('progressbar')).toHaveAttribute('value', '0')
  await path.getByRole('button', { name: /Start Day 1/ }).click()
  await expect(page.locator('#day-roadmap-title')).toContainText('Day 1:')
  await expect(page.locator('.roadmap-task-card')).toHaveCount(17)
  await expect(page.locator('nav button')).toHaveText(['Today', 'Reset', 'My Path', 'Support'])
})

